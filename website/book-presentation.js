export function bookCategory({ id = '', sha256 = '', kind = 'book' }) {
  if (kind !== 'book') return '';
  const sha = sha256 || (id.startsWith('book:public-') ? id.slice('book:public-'.length) : '');
  return categoryBySha.get(sha) || 'other';
}
export function bookCategoryLabel(item) {
  return BOOK_CATEGORIES.find(category => category.id === bookCategory(item))?.label || '';
}
export function libraryBookCategories(items) {
  const counts = new Map();
  for (const item of items) { const category = bookCategory(item); if (category) counts.set(category, (counts.get(category) || 0) + 1); }
  return BOOK_CATEGORIES.filter(category => counts.has(category.id)).map(category => ({ ...category, count: counts.get(category.id) }));
}
/** @template {{id:string,kind:string,title:string,filename:string,sha256?:string}} T
 * @param {T[]} items
 * @param {{query?:string,category?:string,kind?:string}} [filters]
 */
export function filterLibraryItems(items, { query = '', category = '', kind = '' } = {}) {
  const search = query.trim().toLowerCase();
  return items.filter(item => (!kind || item.kind === kind) && (!category || bookCategory(item) === category)
    && `${item.title} ${item.filename}`.toLowerCase().includes(search));
}

/** A title cover is used when the catalogue has no publisher cover artwork. */
export function localizedBookTitle({ zhCN, originalTitle, authorZhCN = '', authorOriginal = '' }) {
  const original = authorOriginal && originalTitle.endsWith(' — Unknown')
    ? originalTitle.slice(0, -'Unknown'.length) + authorOriginal : originalTitle;
  return `${zhCN}${authorZhCN ? ` — ${authorZhCN}` : ''}｜${original}`;
}

export function bookAppearance({ id = '', title = '', kind = 'book' }) {
  // Catalogue titles retain the original for search; keep the cover's Chinese title concise.
  const separator = kind === 'book' ? title.indexOf('｜') : -1;
  const bilingual = separator > 0 && /[\u3400-\u9fff]/.test(title.slice(0, separator));
  const originalTitle = bilingual ? title.slice(separator + 1).trim() : '';
  const heading = bilingual ? title.slice(0, separator).trim() : title;
  const authorSeparator = bilingual ? heading.lastIndexOf(' — ') : -1;
  const author = authorSeparator > 0 ? heading.slice(authorSeparator + 3).trim() : '';
  const displayTitle = author ? heading.slice(0, authorSeparator).trim() : heading;
  const date = displayTitle.match(/\b(\d{4})[.\/-](\d{2})[.\/-](\d{2})\s*$/);
  const name = (date ? displayTitle.slice(0, date.index).replace(/\s*[·|—–-]\s*$/, '') : displayTitle).trim() || title;
  const publication = id.split(':')[0];
  const themes = { economist: 'clay', new_yorker: 'forest', atlantic: 'ink', wired: 'ochre' };
  let hash = 0; for (const character of id || title) hash = (hash * 31 + character.charCodeAt(0)) >>> 0;
  return { name, author, originalTitle, edition: date ? `${date[1]}.${date[2]}.${date[3]}` : '',
    theme: themes[publication] || ['forest', 'clay', 'ink', 'ochre'][hash % 4],
    label: kind === 'magazine' ? 'PERIODICAL' : 'READAGE LIBRARY', kindLabel: kind === 'magazine' ? '整期杂志' : '书籍' };
}
